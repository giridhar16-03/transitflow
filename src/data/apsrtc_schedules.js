export function getScheduleByRoute(routeNo) {
  if (!routeNo) return null;
  const match = APSRTC_SCHEDULES.find((r) => String(r.routeNo).toLowerCase() === String(routeNo).toLowerCase());
  if (!match) {
    const fallback = APSRTC_SCHEDULES.find((r) => {
        let normR = String(r.routeNo).toLowerCase().replace('/', '');
        let normQ = String(routeNo).toLowerCase().replace('/', '');
        return normR.includes(normQ) || normQ.includes(normR);
    });
    return fallback || null;
  }
  return match;
}
